#define NDICT (sizeof(kDict) / sizeof(kDict[0]))

static int isVowelCP(uint32_t c) {
    switch (c) {
        case 0x430: case 0x43E: case 0x443: case 0x44B: case 0x44D:
        case 0x438: case 0x435: case 0x451: case 0x44E: case 0x44F:
            return 1;
    }
    return 0;
}

int STFindStress(const uint32_t *w, size_t len) {
    // "ё" почти всегда ударная — если она есть, словарь не нужен.
    size_t v = 0;
    for (size_t i = 0; i < len; i++) {
        if (isVowelCP(w[i])) { v++; if (w[i] == 0x451) return (int)v; }
    }
    if (len == 0 || len > 40) return 0;

    char buf[96]; size_t bl = 0;
    for (size_t i = 0; i < len && bl + 3 < sizeof(buf); i++) {
        uint32_t cp = w[i];
        if (cp < 0x80) {
            buf[bl++] = (char)cp;
        } else {
            buf[bl++] = (char)(0xC0 | (cp >> 6));
            buf[bl++] = (char)(0x80 | (cp & 0x3F));
        }
    }
    buf[bl] = 0;
    for (size_t i = 0; i < NDICT; i++) {
        if (strcmp(buf, kDict[i].w) == 0) return kDict[i].stress;
    }
    return 0; // не найдено — вызывающий код применит резервное правило
}
