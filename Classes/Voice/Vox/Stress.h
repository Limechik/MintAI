// Stress.h — словарь ударений и резервное правило для незнакомых слов.
#ifndef STRESS_H
#define STRESS_H
#include <stddef.h>
#include <stdint.h>

// Возвращает номер гласной (1-based, считая по порядку гласных букв в слове),
// на которую падает ударение. Если слово не найдено в словаре и не содержит "ё"
// (которая почти всегда ударная), возвращается 0 — вызывающий код должен сам
// применить резервное правило (см. README: по умолчанию — последняя гласная).
int STFindStress(const uint32_t *word, size_t len);

#endif
